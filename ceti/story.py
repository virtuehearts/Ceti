"""Oracle paper writer: StoryBlocks-style long-form generation.

A story is a sequence of blocks, each generated by the oracle
(cloud API) at ~200 words/page and retried if short. Coherence
across 10-50 pages comes from three layers:
  1. story bible — premise, characters, arc, chapter beats
  2. rolling summary of prior blocks
  3. style chunks retrieved from the library (vector memory) —
     voice inspiration, never reproduced

Stories live as plain files:
    data/stories/<id>/
        bible.md  summary.md  blocks/01.md ...  story.md
"""

from __future__ import annotations

import os
import re
import time

from .backends import BackendError
from .retry import retry

WORDS_PER_PAGE = 200
STORIES_DIRNAME = "stories"


class StoryError(Exception):
    """The story run cannot proceed."""


def slugify(text: str) -> str:
    s = re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")
    return s[:40] or "story"


def word_count(text: str) -> int:
    return len(text.split())


_BIBLE_SYSTEM = ("You are a novelist's plotting assistant. Write tight, "
                 "concrete story bibles.")
_BIBLE_USER = """Premise: {premise}

Write a story bible with:
- Title and one-line logline
- Setting (2-3 sentences)
- Main characters (3-6, one line each: who they are, what they want)
- Three-act arc (a paragraph)
- 12 chapter beats (one line each, numbered)

Keep it tight. This bible will guide chapter-by-chapter generation."""

_BLOCK_SYSTEM = ("You are a novelist writing an ORIGINAL novel. Write vivid, "
                 "concrete prose — show, don't tell. The STYLE REFERENCE "
                 "below is voice inspiration only: never reproduce it, "
                 "never quote it, write your own story.")
_BLOCK_USER = """STORY BIBLE:
{bible}

STORY SO FAR (summary of previous chapters):
{summary}

STYLE REFERENCE (voice inspiration from the library — do not copy):
{style}

Write Chapter {n}: {beat}
About {pages} pages (~{words} words). Continue the story seamlessly
from where the summary leaves off. No preamble, no meta-commentary —
just the chapter."""

_EXPAND_USER = """Continue the chapter seamlessly for about {words} more
words. No preamble, no recap — just continue the prose."""

_SUMMARY_SYSTEM = ("You summarize novel chapters for continuity. "
                   "Be concrete: names, events, what changed.")
_SUMMARY_USER = ("Summarize this chapter in ~150 words — who, what "
                 "happened, what changed, any new threads:\n\n{block}")


class StoryWriter:
    """Long-form generation driven by a cloud backend."""

    def __init__(self, cfg, backend, library=None):
        if backend is None or not getattr(backend, "api_key", None):
            raise StoryError(
                "story writer needs a cloud backend with an API key")
        self.cfg = cfg
        self.backend = backend
        self.library = library
        self.root = os.path.join(os.path.abspath(cfg.data_dir),
                                 STORIES_DIRNAME)
        os.makedirs(self.root, exist_ok=True)

    # ---- paths ---------------------------------------------------------
    def _dir(self, story_id: str) -> str:
        d = os.path.join(self.root, story_id)
        if not os.path.isdir(d):
            raise StoryError("no such story: %r" % story_id)
        return d

    def _write(self, path: str, text: str) -> None:
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8") as f:
            f.write(text)

    def _read(self, path: str) -> str:
        with open(path, encoding="utf-8") as f:
            return f.read()

    @staticmethod
    def _block_body(text: str, keep_title: bool = True) -> str:
        """Strip the header we write. keep_title=False also drops
        the '# Chapter N' line (for clean word counts)."""
        text = re.sub(r"^(# Chapter \d+\n\n)_\d+ words_\n\n", r"\1",
                      text, count=1)
        if not keep_title:
            text = re.sub(r"^# Chapter \d+\n\n", "", text, count=1)
        return text

    def _oracle(self, system: str, user: str,
                max_tokens: int = 2000,
                temperature: float = 0.8) -> str:
        try:
            return retry(
                lambda: self.backend.complete(
                    system, user, max_tokens=max_tokens,
                    temperature=temperature),
                attempts=3, exceptions=(BackendError,)).strip()
        except BackendError as e:
            raise StoryError("oracle failed: %s" % e)

    # ---- stories --------------------------------------------------------
    def list_stories(self) -> list[str]:
        return sorted(d for d in os.listdir(self.root)
                      if os.path.isdir(os.path.join(self.root, d)))

    def new_story(self, premise: str, title: str | None = None) -> str:
        premise = (premise or "").strip()
        if not premise:
            raise StoryError("empty premise")
        story_id = "%s-%s" % (slugify(title or premise[:40]),
                              time.strftime("%Y%m%d-%H%M%S"))
        d = os.path.join(self.root, story_id)
        os.makedirs(os.path.join(d, "blocks"))
        bible = self._oracle(_BIBLE_SYSTEM,
                             _BIBLE_USER.format(premise=premise),
                             max_tokens=1500, temperature=0.7)
        self._write(os.path.join(d, "bible.md"), bible)
        self._write(os.path.join(d, "summary.md"),
                    "(no chapters written yet)\n")
        self._write(os.path.join(d, "premise.txt"), premise + "\n")
        return story_id

    def _beats(self, story_id: str) -> list[str]:
        bible = self._read(os.path.join(self._dir(story_id), "bible.md"))
        beats = []
        for line in bible.split("\n"):
            m = re.match(r"\s*\d+[.)]\s+(.*)", line)
            if m:
                beats.append(m.group(1).strip())
        return beats

    def _block_no(self, story_id: str) -> int:
        bdir = os.path.join(self._dir(story_id), "blocks")
        nums = [int(f[:2]) for f in os.listdir(bdir)
                if re.fullmatch(r"\d{2}\.md", f)]
        return max(nums, default=0) + 1

    def _style_ref(self, query: str) -> str:
        if self.library is None:
            return "(no library ingested — pure imagination)"
        try:
            hits = self.library.search(query, top_k=3)
        except Exception:
            return "(library search failed — pure imagination)"
        if not hits:
            return "(no relevant library passages)"
        parts = []
        for h in hits:
            parts.append("[from %s]\n%s"
                         % (h["filename"], h["text"][:1200]))
        return "\n\n---\n\n".join(parts)

    # ---- blocks ----------------------------------------------------------
    def next_block(self, story_id: str, pages: int = 3) -> dict:
        d = self._dir(story_id)
        pages = max(1, min(int(pages), 10))
        n = self._block_no(story_id)
        bible = self._read(os.path.join(d, "bible.md"))
        summary = self._read(os.path.join(d, "summary.md"))
        beats = self._beats(story_id)
        beat = beats[n - 1] if n - 1 < len(beats) else \
            "continue the story toward its climax"
        target_words = pages * WORDS_PER_PAGE
        style = self._style_ref(
            "%s %s" % (beat, summary[-500:]))

        text = self._oracle(
            _BLOCK_SYSTEM,
            _BLOCK_USER.format(bible=bible[:4000], summary=summary[-3000:],
                               style=style[:3600], n=n, beat=beat,
                               pages=pages, words=target_words),
            max_tokens=min(8000, target_words * 2 + 1000),
            temperature=0.8)

        # StoryBlocks rule: retry/expand if the block came up short
        words = word_count(text)
        if words < target_words * 0.7:
            more = self._oracle(
                _BLOCK_SYSTEM,
                _EXPAND_USER.format(
                    words=target_words - words) + "\n\n" + text[-2000:],
                max_tokens=4000, temperature=0.8)
            text = text + "\n\n" + more
            words = word_count(text)

        path = os.path.join(d, "blocks", "%02d.md" % n)
        self._write(path,
                    "# Chapter %d\n\n_%d words_\n\n%s\n" % (n, words, text))

        # roll the summary forward
        chap_sum = self._oracle(
            _SUMMARY_SYSTEM, _SUMMARY_USER.format(block=text[:6000]),
            max_tokens=400, temperature=0.3)
        new_summary = (summary.rstrip() + "\n\nChapter %d: %s"
                       % (n, chap_sum)).strip()
        if len(new_summary) > 3000:  # compress when it gets long
            new_summary = self._oracle(
                _SUMMARY_SYSTEM,
                "Compress this running story summary to ~400 words, "
                "keeping every plot thread:\n\n" + new_summary,
                max_tokens=600, temperature=0.3)
        self._write(os.path.join(d, "summary.md"), new_summary + "\n")
        return {"story_id": story_id, "block": n, "words": words,
                "pages": pages, "path": path}

    def status(self, story_id: str) -> dict:
        d = self._dir(story_id)
        blocks = sorted(f for f in os.listdir(os.path.join(d, "blocks"))
                        if f.endswith(".md"))
        words = 0
        for b in blocks:
            words += word_count(self._block_body(
                self._read(os.path.join(d, "blocks", b)),
                keep_title=False))
        return {"story_id": story_id, "blocks": len(blocks),
                "words": words, "pages": round(words / WORDS_PER_PAGE, 1),
                "dir": d}

    def compile(self, story_id: str) -> dict:
        """Assemble blocks (+ bible) into story.md and story.txt."""
        d = self._dir(story_id)
        bdir = os.path.join(d, "blocks")
        blocks = sorted(f for f in os.listdir(bdir) if f.endswith(".md"))
        if not blocks:
            raise StoryError("no blocks written yet")
        bible = self._read(os.path.join(d, "bible.md"))
        title = bible.split("\n")[0].lstrip("# ").strip() or story_id
        md = ["# %s\n" % title,
              "_A CETI oracle paper — %d chapters_\n" % len(blocks)]
        for b in blocks:
            md.append(self._block_body(
                self._read(os.path.join(bdir, b))).strip())
        story_md = "\n\n---\n\n".join(md) + "\n"
        md_path = os.path.join(d, "story.md")
        self._write(md_path, story_md)
        txt_path = os.path.join(d, "story.txt")
        self._write(txt_path, re.sub(r"[#*_`>]", "", story_md))
        return {"story_id": story_id, "chapters": len(blocks),
                "words": word_count(story_md), "md": md_path,
                "txt": txt_path}


# ---------------------------------------------------------------------------
# Compile-first articles — the bus, not the oracle, writes the article.
#
# Old flow (StoryWriter): bible + rolling summary + library style refs,
# then the oracle writes every chapter. Local knowledge was seasoning.
#
# New flow (ArticleCompiler):
#   1. Bus.compile(topic) — fan out, read EVERY local store per
#      sub-question. Local hits + explicit gap list. No oracle yet.
#   2. Oracle gap-fill ONLY — one call per gap (robust parsing beats
#      one batched call with fragile delimiters), each prompted
#      "answer ONLY this question". UNKNOWN stays a gap, never prose.
#   3. Assemble locally — local frames + gap answers, provenance
#      tagged [aiml]/[memory]/[library]/[oracle gap-fill], gaps
#      still open listed as such. Write article.md + compilation.json.
#
# The article never fails for lack of an oracle: with no backend it
# is written from local knowledge alone, gaps listed as open.
# ---------------------------------------------------------------------------

_GAP_SYSTEM = ("You answer ONE factual question. Answer ONLY that "
               "question in concise factual prose. No preamble, no "
               "extra facts, no meta-commentary. If you do not know, "
               "reply exactly: UNKNOWN")
_GAP_USER = "Question: {q}\n\nAnswer only that question."


class ArticleCompiler:
    """Compile-first articles through the MemoryBus."""

    def __init__(self, cfg, bus, backend=None):
        self.cfg = cfg
        self.bus = bus
        self.backend = backend
        self.root = os.path.join(os.path.abspath(cfg.data_dir),
                                 STORIES_DIRNAME)
        os.makedirs(self.root, exist_ok=True)

    def _oracle_gap(self, question: str) -> str:
        """One gap, one oracle call. UNKNOWN stays a gap."""
        if self.backend is None:
            return "UNKNOWN"
        try:
            ans = retry(
                lambda: self.backend.complete(
                    _GAP_SYSTEM, _GAP_USER.format(q=question),
                    max_tokens=400, temperature=0.2),
                attempts=2, exceptions=(BackendError,)).strip()
        except BackendError:
            return "UNKNOWN"
        return ans or "UNKNOWN"

    def compile_article(self, topic: str,
                        subquestions: list[str] | None = None) -> dict:
        topic = (topic or "").strip()
        if not topic:
            raise StoryError("empty topic")
        comp = self.bus.compile(topic, intent="article",
                                subquestions=subquestions)
        # Gap-fill ONLY — each gap gets one oracle call, never the
        # whole article. Local frames are never sent to the oracle
        # as a writing prompt; the oracle sees one question at a time.
        filled = self.bus.fill_gaps(
            comp, lambda gaps: [self._oracle_gap(q) for q in gaps])
        # Assemble: local first, oracle gap-fills tagged, open gaps listed.
        lines = ["# %s\n" % topic,
                 "_A CETI bus-compiled article — local first, "
                 "oracle gap-fill only_\n",
                 "Local coverage: %.0f%% (%d/%d sub-questions hit "
                 "locally)\n" % (filled.local_coverage * 100,
                                 sum(1 for q in filled.subquestions
                                     if any(_norm_q(f.question) == _norm_q(q)
                                            for f in filled.frames
                                            if f.store != "oracle")),
                                 len(filled.subquestions))]
        seen: set[str] = set()
        for q in filled.subquestions:
            frames = [f for f in filled.frames
                      if _norm_q(f.question) == _norm_q(q)]
            if not frames:
                continue
            lines.append("## %s\n" % q)
            for f in frames:
                key = (f.store, f.text.strip()[:200])
                if key in seen:
                    continue
                seen.add(key)
                tag = ("[oracle gap-fill]" if f.store == "oracle"
                       else "[%s]" % f.store)
                lines.append("%s %s\n" % (tag, f.text.strip()))
        if filled.gaps:
            lines.append("## Open gaps\n")
            lines.append("Local stores + oracle could not answer:\n")
            for g in filled.gaps:
                lines.append("- %s\n" % g.question)
        article = "\n".join(lines) + "\n"
        slug = slugify(topic)
        d = os.path.join(self.root, "%s-article" % slug)
        os.makedirs(d, exist_ok=True)
        md_path = os.path.join(d, "article.md")
        with open(md_path, "w", encoding="utf-8") as f:
            f.write(article)
        import json as _json
        comp_path = os.path.join(d, "compilation.json")
        with open(comp_path, "w", encoding="utf-8") as f:
            _json.dump(filled.to_dict(), f, indent=1)
        return {"topic": topic, "dir": d, "md": md_path,
                "compilation": comp_path,
                "local_coverage": round(filled.local_coverage, 3),
                "gaps_open": len(filled.gaps),
                "gaps_filled": len(comp.gaps) - len(filled.gaps),
                "words": word_count(article)}


def _norm_q(s: str) -> str:
    return re.sub(r"\s+", " ", re.sub(r"[^a-z0-9 ]", "",
                                      (s or "").lower())).strip()

